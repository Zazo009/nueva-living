// The property page template (v2): one template for every development that is not a signature
// page. Each extra module -- specifications, payment timeline, layouts, furniture, walkthrough --
// renders only when the project has the data for it, so nobody sorts pages by hand.
//
// Order: hero and fact strip, the development, homes and prices (with the payment schedule and
// total cost for the chosen home), specifications, gallery, location, on site, our view, project
// FAQ, contact, fine print. Price and availability are never collapsed; long content is, and stays
// in the HTML.
//
// Everything renders inside <main class="v2">; nueva-property-v2.css is scoped to it, so the site
// chrome (top bar, breadcrumb, footer, newsletter) keeps its own styles.
