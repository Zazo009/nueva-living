const AREA_UNIT = { ru: 'м²', ar: 'م²' };
// "works": no licence document seen, but dated evidence of works under way, which Spanish law does
// not allow without a building licence (licence research, 27 November 2026; evidence in crm.licenceEvidence).
const LICENCE_OK = new Set(['first_occupation', 'granted', 'works']);
const VAT = 0.10;
const AJD = 0.012;

// ---------------------------------------------------------------- strings

export function v2t(key, locale, vars = {}, t) {
  const entry = V2_STRINGS[key];
  const value = entry ? (entry[locale] ?? entry.en) : t(key, locale, vars);
  return Object.entries(vars).reduce((acc, [name, val]) => acc.replaceAll(`{${name}}`, String(val)), value);
}

export function assertV2Strings(locales) {
  const missing = [];
  for (const [key, entry] of Object.entries(V2_STRINGS)) {
    for (const locale of locales) if (!entry[locale]) missing.push(`${key} [${locale}]`);
  }
  if (missing.length) throw new Error(`property_v2_strings: ${missing.length} missing translation(s): ${missing.slice(0, 6).join(', ')}`);
}

