// The template's stylesheet is written unscoped in assets/liora/property-v2/ and published scoped
// to .v2, so that `h2`, `.btn` or `.card` there never reach the footer or the top bar.
function scopeSelectors(selectorList) {
  return selectorList.split(',').map((raw) => {
    const sel = raw.trim();
    if (!sel) return sel;
    if (/^(:root|html|body)$/.test(sel)) return '.v2';
    const html = sel.match(/^(html(?:\.[\w-]+|\[[^\]]+\]|:not\([^)]*\))*)\s+(.*)$/);
    if (html) return `${html[1]} .v2 ${html[2].replace(/^body\s+/, '')}`;
    if (/^body\b/.test(sel)) return sel.replace(/^body/, '.v2');
    if (sel.startsWith('.v2')) return sel;
    return `.v2 ${sel}`;
  }).join(',');
}

function scopeCss(css) {
  css = css.replace(/\/\*[\s\S]*?\*\//g, '');
  let out = '';
  let i = 0;
  while (i < css.length) {
    const open = css.indexOf('{', i);
    if (open < 0) break;
    const head = css.slice(i, open).trim();
    let depth = 1;
    let k = open + 1;
    while (k < css.length && depth) { if (css[k] === '{') depth += 1; else if (css[k] === '}') depth -= 1; k += 1; }
    const body = css.slice(open + 1, k - 1);
    if (head.startsWith('@media') || head.startsWith('@supports')) out += `${head}{${scopeCss(body)}}\n`;
    else if (head.startsWith('@')) out += `${head}{${body}}\n`;
    else out += `${scopeSelectors(head)}{${body.trim()}}\n`;
    i = k;
  }
  return out;
}

export function buildV2Stylesheet(root) {
  const dir = path.join(root, 'assets/liora/property-v2');
  const source = ['base.css', 'layer.css'].map((f) => readFileSync(path.join(dir, f), 'utf8')).join('\n');
  const css = `/* Generated by scripts/lib/property_v2.mjs from assets/liora/property-v2/. Edit those. */\n${scopeCss(source)}`;
  const target = path.join(root, 'assets/liora/nueva-property-v2.css');
  if (!existsSync(target) || readFileSync(target, 'utf8') !== css) writeFileSync(target, css);
}

// ---------------------------------------------------------------- helpers

const num = (s) => { const m = String(s ?? '').replace(/,/g, '').match(/\d+(?:\.\d+)?/); return m ? parseFloat(m[0]) : NaN; };
const money = (s) => (/EUR|€/.test(String(s ?? '')) ? num(s) : NaN);
const firstSentence = (s) => { const m = String(s || '').trim().match(/^.*?[.!?。؟](?=\s|$)/); return m ? m[0] : String(s || '').trim(); };

// "€1,234" in English and the locale's own spelling elsewhere, plus a spec the page script can use.
function priceFormatter(locale, PRICE_FORMAT) {
  const fmt = (n) => {
    const en = Math.round(n).toLocaleString('en-GB');
    return locale === 'en' || !PRICE_FORMAT[locale] ? `€${en}` : PRICE_FORMAT[locale](en);
  };
  const sample = fmt(1234567);
  const m = sample.match(/^(\D*)1(\D?)234\D?567(\D*)$/);
  return { fmt, spec: m ? { pre: m[1], sep: m[2], post: m[3] } : { pre: '€', sep: ',', post: '' } };
}

function groupNumber(n, sep) { return Math.round(n).toLocaleString('en-GB').replace(/,/g, sep); }

// "Completion Q4 2027 - Q1 2028" -> "Q4 2027 – Q1 2028" in the page's own language: the label word
// the hero line starts with is dropped when the English source starts with one.
function completionText(project, sourceProject, s) {
  const en = String(sourceProject.hero?.delivery || '');
  const local = String(project.hero?.delivery || en);
  const dropsWord = /^(Completion|Delivery|Delivered|Handover)\s/i.test(en);
  // "Completion to be confirmed": the label is two words in some languages ("Срок сдачи",
  // "Termin odbioru"), so dropping one leaves a fragment; the strip already names it
  if (dropsWord && !/\d/.test(en)) return s('v2.completionTbc');
  return (dropsWord ? local.replace(/^\S+\s+/, '') : local).replace(/\s-\s/g, ' – ');
}

// ---------------------------------------------------------------- the questions

// The project's own questions, less the ones that ask for a fact the page already shows in its key
// facts, price panel or homes table (price, VAT, delivery, what is available, the payment schedule).
// The table, the schedule and the dated price list carry the detail those answers used to repeat, so
// a question stays only when its answer flags something the facts cannot: a conflict between
// documents, a figure no document gives. (Until 26 November 2026 any answer over 120 characters
// stayed, and the visible list opened with "How many homes are available?" and "What do they cost?".) Decided on the English
// record and applied by position, so every language keeps and drops the same questions; the FAQPage
// schema is built from this same list, so it carries exactly what the page shows.
const FACT_QUESTION = /^(is vat included|is iva included|is the price inclusive of vat|when (will it|will they|is it|are they|will the homes?) (be )?(finished|completed|ready|delivered)|when is (delivery|completion|it finished)|what (do|does) (the homes|it|they|a home) cost|how much (do|does|are)|what (is|are) the (starting )?prices?|how many (homes |apartments |villas |units )?are (currently |still )?(available|left|for sale)|what is (available|for sale)|what is the payment (schedule|plan)|how (is|are) (the )?payments? (structured|made|staged))\??$/i;
const SAYS_MORE = /\b(no document|none of the|not (stated|given|published|issued)|does not (say|state|give)|do not (say|state|give)|conflict|differs?|disagrees?|unclear|two figures)\b/i;

export function v2Faqs(sourceProject, project) {
  const src = sourceProject.faq || [];
  const loc = project.faq || src;
  return loc.filter((_, i) => {
    const [q, a] = src[i] || [];
    return !(q && FACT_QUESTION.test(String(q).trim()) && !SAYS_MORE.test(String(a)));
  });
}

